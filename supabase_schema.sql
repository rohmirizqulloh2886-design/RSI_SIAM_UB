-- 0. BERSIHKAN TABEL LAMA (JIKA ADA)
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS catatan_revisi CASCADE;
DROP TABLE IF EXISTS detail_krs CASCADE;
DROP TABLE IF EXISTS krs CASCADE;
DROP TABLE IF EXISTS kelas_mk CASCADE;
DROP TABLE IF EXISTS mata_kuliah CASCADE;
DROP TABLE IF EXISTS periode_krs CASCADE;
DROP TABLE IF EXISTS notifikasi CASCADE;
DROP TABLE IF EXISTS log_aktivitas CASCADE;
DROP TABLE IF EXISTS admin_akademik CASCADE;
DROP TABLE IF EXISTS mahasiswa CASCADE;
DROP TABLE IF EXISTS dosen_pa CASCADE;
DROP TABLE IF EXISTS pengguna CASCADE;

-- -----------------------------------------------------------------------------
-- 1. TABEL PENGGUNA (Entitas: Pengguna)
-- -----------------------------------------------------------------------------
CREATE TABLE pengguna (
  id_pengguna   VARCHAR(10)  PRIMARY KEY,
  username      VARCHAR(30)  NOT NULL UNIQUE,
  password      VARCHAR(255) NOT NULL, -- Disimpan sebagai hash (SHA-256 hex)
  peran         VARCHAR(20)  NOT NULL
                CONSTRAINT chk_pengguna_peran
                CHECK (peran IN ('Mahasiswa', 'Dosen PA', 'Admin Akademik')),
  jumlah_gagal  SMALLINT     NOT NULL DEFAULT 0
                CONSTRAINT chk_pengguna_jumlah_gagal
                CHECK (jumlah_gagal BETWEEN 0 AND 3),
  waktu_kunci   TIMESTAMPTZ  NULL -- NULL jika akun tidak sedang terkunci
);

-- -----------------------------------------------------------------------------
-- 2. TABEL DOSEN_PA (Entitas: DosenPA)
--    Dibuat sebelum mahasiswa, kelas_mk, dan catatan_revisi karena menjadi target FK.
-- -----------------------------------------------------------------------------
CREATE TABLE dosen_pa (
  nidn          VARCHAR(10)  PRIMARY KEY,
  id_pengguna   VARCHAR(10)  NOT NULL UNIQUE
                REFERENCES pengguna(id_pengguna)
                ON UPDATE CASCADE ON DELETE CASCADE,
  nama          VARCHAR(100) NOT NULL
);

-- -----------------------------------------------------------------------------
-- 3. TABEL MAHASISWA (Entitas: Mahasiswa)
-- -----------------------------------------------------------------------------
CREATE TABLE mahasiswa (
  nim               VARCHAR(15)  PRIMARY KEY,
  id_pengguna       VARCHAR(10)  NOT NULL UNIQUE
                    REFERENCES pengguna(id_pengguna)
                    ON UPDATE CASCADE ON DELETE CASCADE,
  nama              VARCHAR(100) NOT NULL,
  ips_semester_lalu NUMERIC(3,2) NOT NULL DEFAULT 0.00
                    CONSTRAINT chk_mahasiswa_ips
                    CHECK (ips_semester_lalu BETWEEN 0.00 AND 4.00),
  id_dosen_pa       VARCHAR(10)  NOT NULL
                    REFERENCES dosen_pa(nidn)
                    ON UPDATE CASCADE ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- 4. TABEL ADMIN_AKADEMIK (Entitas: AdminAkademik)
-- -----------------------------------------------------------------------------
CREATE TABLE admin_akademik (
  nip           VARCHAR(18)  PRIMARY KEY,
  id_pengguna   VARCHAR(10)  NOT NULL UNIQUE
                REFERENCES pengguna(id_pengguna)
                ON UPDATE CASCADE ON DELETE CASCADE,
  nama          VARCHAR(100) NOT NULL
);

-- -----------------------------------------------------------------------------
-- 5. TABEL LOG_AKTIVITAS (Entitas: LogAktivitas)
-- -----------------------------------------------------------------------------
CREATE TABLE log_aktivitas (
  id_log        INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna   VARCHAR(10)  NOT NULL
                REFERENCES pengguna(id_pengguna)
                ON UPDATE CASCADE ON DELETE CASCADE,
  aktivitas     VARCHAR(100) NOT NULL,
  waktu         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- 6. TABEL NOTIFIKASI (Entitas: Notifikasi)
-- -----------------------------------------------------------------------------
CREATE TABLE notifikasi (
  id_notifikasi INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_penerima   VARCHAR(10)  NOT NULL
                REFERENCES pengguna(id_pengguna)
                ON UPDATE CASCADE ON DELETE CASCADE,
  pesan         VARCHAR(255) NOT NULL,
  waktu_kirim   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sudah_dibaca  BOOLEAN      NOT NULL DEFAULT FALSE
);

-- -----------------------------------------------------------------------------
-- 7. TABEL PERIODE_KRS (Entitas: PeriodeKRS)
-- -----------------------------------------------------------------------------
CREATE TABLE periode_krs (
  id_periode      VARCHAR(10) PRIMARY KEY,
  semester        VARCHAR(20) NOT NULL,
  tanggal_mulai   DATE        NOT NULL,
  tanggal_selesai DATE        NOT NULL,
  CONSTRAINT chk_periode_tanggal CHECK (tanggal_selesai >= tanggal_mulai)
);

-- -----------------------------------------------------------------------------
-- 8. TABEL MATA_KULIAH (Entitas: MataKuliah)
-- -----------------------------------------------------------------------------
CREATE TABLE mata_kuliah (
  kode_mk   VARCHAR(10)  PRIMARY KEY,
  nama_mk   VARCHAR(100) NOT NULL,
  sks       SMALLINT     NOT NULL
            CONSTRAINT chk_mk_sks CHECK (sks BETWEEN 1 AND 6),
  semester  SMALLINT     NOT NULL
            CONSTRAINT chk_mk_semester CHECK (semester BETWEEN 1 AND 8)
);

-- -----------------------------------------------------------------------------
-- 9. TABEL KELAS_MK (Entitas: KelasMK)
-- -----------------------------------------------------------------------------
CREATE TABLE kelas_mk (
  id_kelas    VARCHAR(15) PRIMARY KEY,
  kode_mk     VARCHAR(10) NOT NULL
              REFERENCES mata_kuliah(kode_mk)
              ON UPDATE CASCADE ON DELETE RESTRICT,
  id_periode  VARCHAR(10) NOT NULL
              REFERENCES periode_krs(id_periode)
              ON UPDATE CASCADE ON DELETE RESTRICT,
  id_dosen    VARCHAR(10) NOT NULL
              REFERENCES dosen_pa(nidn)
              ON UPDATE CASCADE ON DELETE RESTRICT,
  hari        VARCHAR(10) NOT NULL
              CONSTRAINT chk_kelas_hari
              CHECK (hari IN ('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu')),
  jam_mulai   TIME        NOT NULL,
  jam_selesai TIME        NOT NULL,
  ruangan     VARCHAR(20) NOT NULL,
  kuota_maks  SMALLINT    NOT NULL
              CONSTRAINT chk_kelas_kuota CHECK (kuota_maks >= 0),
  CONSTRAINT chk_kelas_jam CHECK (jam_selesai > jam_mulai),
  -- Mencegah bentrok ruangan & dosen pada jam mulai yang sama dalam satu periode (UC-11)
  CONSTRAINT uq_kelas_ruangan_jadwal UNIQUE (id_periode, ruangan, hari, jam_mulai),
  CONSTRAINT uq_kelas_dosen_jadwal   UNIQUE (id_periode, id_dosen, hari, jam_mulai)
);

-- -----------------------------------------------------------------------------
-- 10. TABEL KRS (Entitas: KRS)
-- -----------------------------------------------------------------------------
CREATE TABLE krs (
  id_krs            VARCHAR(15) PRIMARY KEY,
  nim               VARCHAR(15) NOT NULL
                    REFERENCES mahasiswa(nim)
                    ON UPDATE CASCADE ON DELETE CASCADE,
  id_periode        VARCHAR(10) NOT NULL
                    REFERENCES periode_krs(id_periode)
                    ON UPDATE CASCADE ON DELETE RESTRICT,
  status            VARCHAR(20) NOT NULL DEFAULT 'KRS Sementara'
                    CONSTRAINT chk_krs_status
                    CHECK (status IN (
                      'KRS Sementara',
                      'Menunggu Persetujuan',
                      'Disetujui',
                      'Perlu Revisi'
                    )),
  tanggal_pengajuan TIMESTAMPTZ NULL, -- NULL selama masih 'KRS Sementara'
  total_sks         SMALLINT    NOT NULL DEFAULT 0
                    CONSTRAINT chk_krs_total_sks CHECK (total_sks BETWEEN 0 AND 24),
  -- Satu mahasiswa hanya memiliki satu KRS per periode akademik
  CONSTRAINT uq_krs_mahasiswa_periode UNIQUE (nim, id_periode)
);

-- -----------------------------------------------------------------------------
-- 11. TABEL DETAIL_KRS (Entitas: DetailKRS)
--     Composite PK (id_krs, id_kelas) mencegah kelas yang sama dipilih dua kali.
--     ON DELETE RESTRICT pada id_kelas menjaga aturan UC-11 (kelas yang sudah
--     terdaftar di KRS mahasiswa tidak boleh dihapus).
-- -----------------------------------------------------------------------------
CREATE TABLE detail_krs (
  id_krs    VARCHAR(15) NOT NULL
            REFERENCES krs(id_krs)
            ON UPDATE CASCADE ON DELETE CASCADE,
  id_kelas  VARCHAR(15) NOT NULL
            REFERENCES kelas_mk(id_kelas)
            ON UPDATE CASCADE ON DELETE RESTRICT,
  PRIMARY KEY (id_krs, id_kelas)
);

-- -----------------------------------------------------------------------------
-- 12. TABEL CATATAN_REVISI (Entitas: CatatanRevisi)
-- -----------------------------------------------------------------------------
CREATE TABLE catatan_revisi (
  id_catatan  INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_krs      VARCHAR(15) NOT NULL
              REFERENCES krs(id_krs)
              ON UPDATE CASCADE ON DELETE CASCADE,
  id_dosen_pa VARCHAR(10) NOT NULL
              REFERENCES dosen_pa(nidn)
              ON UPDATE CASCADE ON DELETE RESTRICT,
  catatan     TEXT        NOT NULL
              CONSTRAINT chk_catatan_tidak_kosong CHECK (LENGTH(TRIM(catatan)) > 0),
  tanggal     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- INDEKS TAMBAHAN UNTUK PERFORMA QUERY
-- -----------------------------------------------------------------------------
CREATE INDEX idx_mahasiswa_dosen_pa   ON mahasiswa(id_dosen_pa);
CREATE INDEX idx_log_pengguna         ON log_aktivitas(id_pengguna, waktu DESC);
CREATE INDEX idx_notifikasi_penerima  ON notifikasi(id_penerima, sudah_dibaca);
CREATE INDEX idx_kelas_periode        ON kelas_mk(id_periode);
CREATE INDEX idx_kelas_kode_mk        ON kelas_mk(kode_mk);
CREATE INDEX idx_kelas_dosen          ON kelas_mk(id_dosen);
CREATE INDEX idx_krs_status           ON krs(status);
CREATE INDEX idx_detail_krs_kelas     ON detail_krs(id_kelas);
CREATE INDEX idx_catatan_krs          ON catatan_revisi(id_krs, tanggal DESC);

